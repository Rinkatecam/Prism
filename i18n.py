# Per-language merged view cache. TRANSLATIONS is static at runtime, so each
# language's English-backed merge is computed once. Cleared by tests that inject
# synthetic locales.
_MERGED_CACHE: dict = {}


def get_translations(lang: str) -> dict:
    """Return the translation dict for ``lang``, backed by English.

    Missing keys fall back to the English string so a partially-translated
    locale renders English text instead of a BLANK label. Unknown languages
    return English. The returned dict is treated as read-only by callers.
    """
    cached = _MERGED_CACHE.get(lang)
    if cached is not None:
        return cached
    base = TRANSLATIONS["en"]
    lang_map = TRANSLATIONS.get(lang)
    if lang_map is None or lang_map is base:
        merged = dict(base)
    else:
        merged = {**base, **lang_map}
    _MERGED_CACHE[lang] = merged
    return merged
